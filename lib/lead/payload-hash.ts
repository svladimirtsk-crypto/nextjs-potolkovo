/**
 * PT-009 · Авторитетный отпечаток payload — только сервер.
 *
 * Хранится в `leads.payload_hash` и решает две задачи:
 *
 *  1. идемпотентность: тот же `requestId` с тем же хешем — повтор прежнего
 *     результата без побочных эффектов, с другим хешем — `409`;
 *  2. честный дедуп: заявка с тем же телефоном считается дублем, только если
 *     совпадает и содержимое. Раньше `findRecentByPhone` возвращал ЛЮБУЮ
 *     недавнюю заявку с тем же номером, поэтому полная заявка, отправленная
 *     через минуту после rescue, молча получала код короткой rescue-заявки, а
 *     её состав не сохранялся нигде.
 *
 * Считается от zod-разобранного payload: телефон уже нормализован, дефолты
 * подставлены, неизвестные ключи отброшены схемой. Хеш от «сырого» тела
 * запроса плясал бы от порядка ключей и лишних полей клиента.
 */
import { createHash } from "node:crypto";

import { leadPayloadFingerprint } from "./canonical";

/** sha256 канонического payload, hex. */
export function hashLeadPayload(payload: Record<string, unknown>): string {
  return createHash("sha256").update(leadPayloadFingerprint(payload)).digest("hex");
}
